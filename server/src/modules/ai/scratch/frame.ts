export const SCRATCH_MODES = ['SHELF', 'ANCHORS'] as const;

export type ScratchMode = (typeof SCRATCH_MODES)[number];

export const isScratchMode = (value: unknown): value is ScratchMode =>
  typeof value === 'string' &&
  (SCRATCH_MODES as readonly string[]).includes(value);

