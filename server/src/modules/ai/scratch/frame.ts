import { COLLAGE_REWRITE_FRAME } from '~/modules/ai/rewrite/frame';

/**
 * Рамка «С нуля» — рамка правки склейки, где склейка собрана из строк кумиров.
 * MAJOR — другой подход, MINOR — новое правило или другое содержимое запроса, PATCH — формулировка.
 * 1.0.0 — Explore: трек по теме и трём эталонам. 2.0.0 — склейка из полки, пересборка рамкой правки 2.2.0.
 */
export const SCRATCH_FRAME_VERSION = '2.0.0';

/** Пункт рамки правки → его замена для «С нуля»; `null` — пункт убрать. */
export const SCRATCH_FRAME_REPLACEMENTS: readonly (readonly [
  string,
  string | null,
])[] = [
  [
    'Склейка — черновик: мотивы, слова-находки и звук. Готовых строк в ней мало.',
    'Склейка собрана из строк артистов, которых любит автор. Их мир, словарь и находки бери: это и мир автора.',
  ],
  [
    '- Перепиши почти каждую строку. Дословно из склейки остаётся не больше трети строк — те, что уже бьют целиком: панч, мат, абсурд одной фразой, образ с подтекстом. Их не трогай.',
    '- Перепиши каждую строку. Дословно из склейки не оставляй ни одной: это чужие строки. Бери ядро — образ, слово-находку, сленг, англицизм, игру слов — и строй строку заново.',
  ],
  [
    '- Строку, которую оставляешь дословно, под звук четверостишия не подгоняй: новые строки подстраивай под неё. Не встаёт — пусть четверостишие будет неровным.',
    null,
  ],
  [
    '- Под частью — карточки приёмов. Возьми один-два, если ложатся. Ради галочки не вставляй.',
    null,
  ],
];

export const buildScratchFrame = (base: string): string =>
  base
    .split('\n')
    .flatMap((line) => {
      const replacement = SCRATCH_FRAME_REPLACEMENTS.find(
        ([from]) => from === line
      );
      if (!replacement) {
        return [line];
      }

      return replacement[1] === null ? [] : [replacement[1]];
    })
    .join('\n');

export const buildScratchSystem = (): string =>
  buildScratchFrame(COLLAGE_REWRITE_FRAME);
