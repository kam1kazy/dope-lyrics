export const buildScratchFrame = (base: string): string =>
  base
    .split('\n')
    .flatMap((line) => {
      const replacement = SCRATCH_FRAME_REPLACEMENTS.find(
        ([from]) => from === line
      );
      if (!replacement) {
        return [line];
      }

      return replacement[1] === null ? [] : [replacement[1]];
    })
    .join('\n');

export const buildScratchSystem = (): string =>
  buildScratchFrame(COLLAGE_REWRITE_FRAME);
