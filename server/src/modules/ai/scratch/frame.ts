export const replaceFrameLines = (
  base: string,
  replacements: typeof SCRATCH_ANCHOR_REPLACEMENTS
): string =>
  base
    .split('\n')
    .flatMap((line) => {
      const replacement = replacements.find(([from]) => from === line);
      if (!replacement) {
        return [line];
      }

      return replacement[1] === null ? [] : [replacement[1]];
    })
    .join('\n');

export const buildScratchSystem = (mode: ScratchMode): string =>
  mode === 'SHELF'
    ? SCRATCH_SHELF_FRAME
    : replaceFrameLines(SCRATCH_SHELF_FRAME, SCRATCH_ANCHOR_REPLACEMENTS);
